CREATE TABLE IF NOT EXISTS SOLICITUDES_HTTP (
    ID_SOLICITUD VARCHAR(36) NOT NULL,
    SIMULACION_ID VARCHAR NOT NULL,
    LOTE_ID VARCHAR NOT NULL,
    SESION_KEY NUMBER(38,0) NOT NULL,
    FECHA_SIMULADA DATE NOT NULL,
    CODIGO_HTTP INTEGER,
    LATENCIA_HTTP_MS FLOAT NOT NULL,
    ERROR_TRANSPORTE BOOLEAN NOT NULL,
    ID_PREDICCION VARCHAR(36),
    FECHA_REGISTRO TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (ID_SOLICITUD)
);
