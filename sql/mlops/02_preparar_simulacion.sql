-- ============================================================
-- 2. Crear tabla de control de lotes
-- ============================================================

CREATE TABLE IF NOT EXISTS LOTES_PRODUCCION (

    SIMULACION_ID VARCHAR(100) NOT NULL,
    LOTE_ID VARCHAR(50) NOT NULL,
    NUMERO_LOTE INTEGER NOT NULL,

    FECHA_INICIO DATE NOT NULL,
    FECHA_FIN DATE NOT NULL,

    FECHA_PROCESAMIENTO_SIMULADA DATE NOT NULL,
    FECHA_MADURACION DATE NOT NULL,
    FECHA_EVALUACION_SIMULADA DATE,

    TOTAL_OBSERVACIONES INTEGER NOT NULL,
    TOTAL_PREDICCIONES INTEGER DEFAULT 0,
    TOTAL_ERRORES INTEGER DEFAULT 0,

    ESTADO VARCHAR(30) DEFAULT 'pendiente',

    VERSION_MODELO VARCHAR(100),
    RUN_ID VARCHAR(100),
    HASH_DATASET VARCHAR(64),
    SNAPSHOT_ID VARCHAR(100),

    DERIVA_INDUCIDA BOOLEAN DEFAULT FALSE,
    ESCENARIO_DERIVA VARCHAR,

    FECHA_REGISTRO TIMESTAMP_TZ
        DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_LOTES_PRODUCCION
        PRIMARY KEY (SIMULACION_ID, LOTE_ID)

);

-- ============================================================
-- 3. Verificar estructuras
-- ============================================================

DESCRIBE TABLE PREDICCIONES;

DESCRIBE TABLE LOTES_PRODUCCION;

SELECT ORIGEN, COUNT(*) AS TOTAL
FROM PREDICCIONES
GROUP BY ORIGEN;

SELECT COUNT(*) AS TOTAL_LOTES
FROM LOTES_PRODUCCION;
