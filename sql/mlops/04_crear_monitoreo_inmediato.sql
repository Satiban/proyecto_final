USE DATABASE ORALSOLUTIONS_DW;
USE SCHEMA MLOPS;

CREATE TABLE IF NOT EXISTS MONITOREO_INMEDIATO (
    SIMULACION_ID VARCHAR NOT NULL, LOTE_ID VARCHAR NOT NULL,
    FECHA_SIMULADA DATE NOT NULL, VERSION_MODELO VARCHAR NOT NULL,
    RUN_ID VARCHAR NOT NULL, HASH_DATASET VARCHAR NOT NULL, SNAPSHOT_ID VARCHAR NOT NULL,
    DERIVA_INDUCIDA BOOLEAN NOT NULL, TOTAL_PREDICCIONES INTEGER NOT NULL,
    PSI_MAX FLOAT, FEATURE_PSI_MAX VARCHAR, MUESTRA_PEQUENA BOOLEAN,
    PCT_FALTANTES_MAX FLOAT, PCT_FUERA_RANGO_MAX FLOAT, PCT_CATEGORIAS_NO_VISTAS_MAX FLOAT,
    PROBABILIDAD_PROMEDIO FLOAT, PROBABILIDAD_P05 FLOAT, PROBABILIDAD_P50 FLOAT,
    PROBABILIDAD_P95 FLOAT, TASA_CONTACTAR FLOAT,
    LATENCIA_INFERENCIA_P50_MS FLOAT, LATENCIA_INFERENCIA_P95_MS FLOAT,
    VOLUMEN_HTTP INTEGER, ERRORES_4XX INTEGER, ERRORES_5XX INTEGER,
    TASA_ERROR_HTTP FLOAT, LATENCIA_HTTP_P50_MS FLOAT, LATENCIA_HTTP_P95_MS FLOAT,
    FECHA_REGISTRO TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (SIMULACION_ID, LOTE_ID)
);
CREATE TABLE IF NOT EXISTS DERIVA_FEATURES (
    SIMULACION_ID VARCHAR NOT NULL, LOTE_ID VARCHAR NOT NULL, FEATURE VARCHAR NOT NULL,
    TIPO VARCHAR, PSI FLOAT, PRUEBA_ESTADISTICA VARCHAR, ESTADISTICO FLOAT,
    P_VALOR FLOAT, PRUEBA_VALIDA BOOLEAN, PCT_FALTANTES FLOAT, PCT_FUERA_RANGO FLOAT,
    CATEGORIAS_NO_VISTAS INTEGER, PCT_CATEGORIAS_NO_VISTAS FLOAT,
    PRIMARY KEY (SIMULACION_ID, LOTE_ID, FEATURE)
);
CREATE TABLE IF NOT EXISTS ALERTAS (
    SIMULACION_ID VARCHAR NOT NULL, LOTE_ID VARCHAR NOT NULL, FASE VARCHAR NOT NULL,
    CODIGO VARCHAR NOT NULL, FECHA_SIMULADA DATE NOT NULL, METRICA VARCHAR,
    VALOR_OBSERVADO FLOAT, UMBRAL VARCHAR, VENTANA VARCHAR, SEVERIDAD VARCHAR,
    DESTINATARIO VARCHAR, ACCION VARCHAR, FECHA_REGISTRO TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (SIMULACION_ID, LOTE_ID, FASE, CODIGO)
);
