-- Métricas supervisadas de producción; las métricas inmediatas de deriva
-- y del sistema se incorporarán en la siguiente fase.
CREATE TABLE IF NOT EXISTS ORALSOLUTIONS_DW.MLOPS.MONITOREO (
    SIMULACION_ID VARCHAR(100) NOT NULL,
    LOTE_ID VARCHAR(50) NOT NULL,
    FECHA_EVALUACION_SIMULADA DATE NOT NULL,
    VERSION_MODELO VARCHAR(100) NOT NULL,
    RUN_ID VARCHAR(100) NOT NULL,
    SNAPSHOT_ID VARCHAR(100) NOT NULL,
    HASH_DATASET VARCHAR(64) NOT NULL,
    DERIVA_INDUCIDA BOOLEAN NOT NULL,
    TOTAL_OBSERVACIONES INTEGER NOT NULL,
    ABANDONOS INTEGER NOT NULL,
    TASA_ABANDONO FLOAT NOT NULL,
    PR_AUC FLOAT,
    PRECISION FLOAT NOT NULL,
    RECALL FLOAT,
    TP INTEGER NOT NULL,
    FP INTEGER NOT NULL,
    FN INTEGER NOT NULL,
    TN INTEGER NOT NULL,
    TASA_CONTACTAR FLOAT NOT NULL,
    PROBABILIDAD_PROMEDIO FLOAT NOT NULL,
    LATENCIA_INFERENCIA_P50_MS FLOAT NOT NULL,
    LATENCIA_INFERENCIA_P95_MS FLOAT NOT NULL,
    COSTO_MODELO_USD FLOAT NOT NULL,
    COSTO_REGLA_1_SESION_USD FLOAT NOT NULL,
    COSTO_LLAMAR_TODOS_USD FLOAT NOT NULL,
    COSTO_NO_HACER_NADA_USD FLOAT NOT NULL,
    FECHA_REGISTRO TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_MONITOREO PRIMARY KEY (SIMULACION_ID, LOTE_ID)
);